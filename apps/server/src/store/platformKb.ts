export function ensurePlatformKb(repos: Repos): void {
  const existing = new Set(repos.listPlatformKb().map((e) => e.title));
  const ts = nowIso();
  for (const seed of PLATFORM_KB_SEEDS) {
    if (existing.has(seed.title)) continue;
    const row: KbRow = {
      id: uid('kb'),
      title: seed.title,
      body: seed.body,
      scope: 'platform',
      scope_id: null,
      tags: JSON.stringify(seed.tags),
      enabled: 1,
      created_at: ts,
      updated_at: ts,
      workspace_id: null,
      owner_user_id: null,
    };
    repos.insertKb(row);
  }
}
